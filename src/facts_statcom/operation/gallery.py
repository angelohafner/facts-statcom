"""A static, self-contained HTML gallery for editable operation SVG charts."""

from __future__ import annotations

from html import escape
from pathlib import Path
from typing import Mapping

DESCRIPTIONS: Mapping[str, str] = {
    "reactive-power-vs-e": "How converter voltage magnitude determines injected reactive power.",
    "reactive-current-vs-e": "Relation between converter voltage and capacitive injected current.",
    "phasor-capacitive": "VSC-to-PCC current direction for capacitive operation.",
    "phasor-inductive": "Phasor reversal when the STATCOM absorbs reactive power.",
    "power-angle": "Illustrative active and reactive power dependence on phase angle.",
    "v-i-droop": "Voltage-regulation droop slope and converter current saturation.",
    "reactive-current-limit": "Why constant rated reactive current does not mean constant Q.",
    "waveforms-capacitive": "One-phase fundamental voltage and injected current waveforms.",
    "waveforms-inductive": "Reversed injected-current quadrature relationship.",
    "voltage-response": "PCC voltage response to grid voltage step changes.",
    "current-response": "Simplified PI reference and current tracking.",
    "reactive-power-response": "Capacitive injection and inductive absorption during control.",
    "converter-voltage-response": "Fundamental converter voltage required by the current model.",
}


def save_gallery(output_dir: Path, generated: list[dict[str, object]]) -> Path:
    """Generate an offline page using the exact files in a saved manifest."""
    cards = []
    for entry in generated:
        key = str(entry["figure"])
        files = [str(name) for name in entry["files"]]
        if not files or any(Path(file).name != file for file in files):
            raise ValueError("Only filenames relative to the gallery may be used")
        image = next((f for f in files if f.endswith(".svg")), files[0])
        links = " · ".join(
            f'<a href="{escape(file, quote=True)}">{escape(Path(file).suffix[1:].upper())}</a>'
            for file in files
        )
        cards.append(
            f'<article><a href="{escape(image, quote=True)}">'
            f'<img src="{escape(image, quote=True)}" loading="lazy" '
            f'alt="{escape(key, quote=True)} figure"></a>'
            f'<h2>{escape(key.replace("-", " ").title())}</h2>'
            f'<p>{escape(DESCRIPTIONS.get(key, "STATCOM operating diagram"))}</p>'
            f'<p class="links">{links}</p></article>'
        )
    content = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>STATCOM operating-point gallery</title>
<style>
:root { color-scheme: light; font-family: system-ui, -apple-system, Segoe UI, sans-serif; }
body { background:#F4F7FB; color:#24364A; margin:0 auto; padding:32px 24px 60px; max-width:1450px; }
header { max-width:1100px; margin:0 auto 34px; }
h1 { font-size:clamp(24px,3vw,37px); margin:0 0 12px; }
header p { font-size:16px; line-height:1.55; color:#697B90; }
a { color:#137F78; }
.grid { display:grid; grid-template-columns:repeat(auto-fit,minmax(310px,1fr)); gap:22px; }
article { background:white; border:1px solid #D9E3ED; padding:14px; border-radius:9px; }
article img { display:block; width:100%; background:white; min-height:165px; object-fit:contain; border-bottom:1px solid #D9E3ED; }
article h2 { font-size:17px; margin:18px 0 5px; }
article p { margin:6px 0 12px; color:#697B90; line-height:1.45; }
article .links { margin-top:12px; }
</style>
</head>
<body>
<header><h1>STATCOM — operation &amp; voltage-control plots</h1>
<p>Editable vector figures derived from a lossless fundamental phasor model and an
educational averaged PI control surrogate. <strong>Not EMT, harmonic, or switching
simulation.</strong> Positive injected Q means capacitive support; current points
from converter to PCC. Independent of the schematic drawing engine.</p>
<p>See <code>docs/operation.md</code> for exact sign conventions, equations and limits.
All figures are generated by <code>python -m facts_statcom.operation --all</code>.</p>
</header>
<main class="grid">""" + "\n".join(cards) + """</main>
</body>
</html>
"""
    output = output_dir / "index.html"
    output.write_text(content, encoding="utf-8")
    return output
